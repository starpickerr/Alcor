def fixtures(profile):
    sys.path.insert(0, str(desktop.ROOT / 'packages/stella-secretary'))
    from business.worker import Business
    business = Business(profile / 'stella/business')
    today = datetime.now().astimezone().date().isoformat()
    zone = str(Path('/etc/localtime').resolve()).split('/zoneinfo/')[-1]
    offset = datetime.now().astimezone().strftime('%z')
    offset = offset[:3] + ':' + offset[3:]
    event_group = business.calendar.create_category({'name':'课程','color':'#18B9D5'})
    target = business.calendar.create_category({'name':'工作','color':'#AF79D4'})
    task_group = business.tasks.create_category({'name':'planA','color':'#6B8AF7'})
    task_target = business.tasks.create_category({'name':'学习','color':'#4CB69B'})
    event = business.calendar.create_event({'repeat_timezone':zone,'title':'计算机网络 · 协议与传输','description':'预习第三章，整理课堂笔记。','category_id':event_group['id'],'start_at':f'{today}T09:55:00{offset}','end_at':f'{today}T12:30:00{offset}','location':'HGX502','url':'https://example.com/course','alarms':[{'offset':-900}]})
    all_day = business.calendar.create_event({'repeat_timezone':zone,'title':'全天阅读','category_id':event_group['id'],'start_at':f'{today}T00:00:00{offset}','end_at':f'{(datetime.fromisoformat(today)+timedelta(days=1)).date().isoformat()}T00:00:00{offset}','all_day':True})
    task = business.tasks.create_todo({'timezone':zone,'title':'2026秋Python · 07 turtle','notes':'完成 turtle 练习，记录绘图步骤。','due_on':today,'due_time':'13:30','category_id':task_group['id'],'priority':3,'flagged':True,'tags':['Python','课程'],'url':'https://example.com/turtle','repeat_frequency':'none'})
    readonly = business.calendar.create_event({'repeat_timezone':zone,'title':'订阅课程（只读）','category_id':event_group['id'],'start_at':f'{today}T14:00:00{offset}','end_at':f'{today}T15:00:00{offset}'})
    business.calendar.apple_bind('item',readonly['id'],{'apple_id':'readonly','group_id':'synthetic','can_modify':False,'can_delete':False})
    pending = business.calendar.create_event({'repeat_timezone':zone,'title':'等待确认的日程','category_id':event_group['id'],'start_at':f'{today}T15:00:00{offset}','end_at':f'{today}T16:00:00{offset}'})
    business.calendar.apple_bind('item',pending['id'],{'apple_id':'pending','group_id':'synthetic','can_modify':True,'can_delete':True})
    business.calendar.delete_event(pending['id'])
    anchor = (datetime.fromisoformat(today)-timedelta(days=30)).date().isoformat()
    repeating = business.tasks.create_todo({'timezone':zone,'title':'重复阅读计划','due_on':anchor,'repeat_frequency':'daily','category_id':task_group['id']})
    readonly_task=business.tasks.create_todo({'title':'只读事务','category_id':task_group['id']})
    business.tasks.apple_bind('item',readonly_task['id'],{'apple_id':'readonly-task','can_modify':False,'can_delete':False})
    pending_task=business.tasks.create_todo({'title':'待确认事务','category_id':task_group['id']})
    business.tasks.apple_bind('item',pending_task['id'],{'apple_id':'pending-task','can_modify':True,'can_delete':True})
    business.tasks.delete_todo(pending_task['id'])
    business.meta.close()
    return dict(readonly_task=readonly_task,pending_task=pending_task,event=event,task=task,readonly=readonly,pending=pending,all_day=all_day,target=target,task_target=task_target,repeating=repeating,anchor=anchor)


