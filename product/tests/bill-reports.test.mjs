import test from 'node:test'
import assert from 'node:assert/strict'
import { mkdtemp, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { BusinessWorker } from '../../packages/alcor-organizer/src/business.js'

test('bill reports share posted ledger totals, categories, rankings and day groups across edits and deletes', async t => {
  const root = await mkdtemp(join(tmpdir(), 'stella-bill-reports-'))
  const worker = new BusinessWorker(root, { worker: new URL('../../packages/alcor-secretary/business/worker.py', import.meta.url) })
  t.after(async () => { await worker.close(); await rm(root, { recursive: true, force: true }) })
  const call = (method, args = {}) => worker.call('invoke', { domain: 'bills', method, arguments: args })
  const add = (name, amount_minor, extra = {}) => call('create_ledger', { name, amount_minor, currency: 'CNY', entry_type: 'expense', occurred_at: '2026-09-27T17:00:00+08:00', category: '餐饮', ...extra })
  const lunch = await add('午餐', 1234)
  await add('午餐', 66)
  await add('地铁', 200, { category: '交通', occurred_at: '2026-09-28T00:10:00+08:00' })
  await add('工资', 3000, { entry_type: 'income', category: '收入' })
  await add('Pending', 9999, { status: 'pending' })
  await add('Reversed', 8888, { status: 'reversed' })
  await add('Yen', 300, { currency: 'JPY' })
  const reports = await call('statement_reports', { period_type: 'monthly', year: 2026 })
  const report = reports.find(row => row.currency === 'CNY')
  assert.equal(report.expense_minor, '1500')
  assert.equal(report.income_minor, '3000')
  assert.equal(report.net_minor, '1500')
  assert.deepEqual(report.categories.expense.map(row => [row.category, row.amount_minor]), [['餐饮', '1300'], ['交通', '200']])
  assert.equal(report.rankings.expense[0].name, '午餐')
  assert.equal(report.rankings.expense[0].entry_count, 2)
  assert.equal(report.rankings.expense[0].share_basis_points, 8667)
  assert.equal(reports.find(row => row.currency === 'JPY').expense_minor, '300')
  const ledger = await call('ledger_report', { start: '2026-09-01', end: '2026-09-30' })
  assert.deepEqual(ledger.days.map(row => row.date), ['2026-09-28', '2026-09-27'])
  assert.equal(ledger.days[0].totals[0].expense_minor, '200')
  assert.equal(ledger.totals.find(row => row.currency === 'CNY').expense_minor, report.expense_minor)
  const projection = (await worker.call('records')).find(row => row.id === lunch.id)
  await worker.call('archive', { record_id: lunch.id, expected_revision: projection.revision, archived: true })
  assert.equal((await call('ledger_report', { start: '2026-09-01', end: '2026-09-30' })).totals.find(row => row.currency === 'CNY').expense_minor, '1500')
  await call('update_ledger', { id: lunch.id, patch: { occurred_at: '2026-10-01T00:00:00+08:00', currency: 'USD', category: '工作' }, expectedRevision: lunch.revision })
  let updated = await call('statement_reports', { period_type: 'monthly', year: 2026 })
  assert.equal(updated.find(row => row.currency === 'CNY').expense_minor, '266')
  assert.equal(updated.find(row => row.currency === 'USD').categories.expense[0].category, '工作')
  const snapshot = await call('get_ledger', { id: lunch.id })
  await worker.call('commit_bill_delete', { entry_id: lunch.id, revision: snapshot.revision, snapshot, operation_id: 'b'.repeat(64) })
  updated = await call('statement_reports', { period_type: 'monthly', year: 2026 })
  assert.equal(updated.some(row => row.currency === 'USD'), false)
  assert.equal((await call('statement_reports', { period_type: 'yearly', year: 2026 })).find(row => row.currency === 'CNY').expense_minor, '266')
  await add('Large', 9007199254740991)
  const large = (await call('statement_reports', { period_type: 'monthly', year: 2026 })).find(row => row.currency === 'CNY')
  assert.equal(large.expense_minor, '9007199254741257')
  assert.equal((await call('ledger_report', { start: '2026-09-01', end: '2026-09-30' })).totals.find(row => row.currency === 'CNY').expense_minor, large.expense_minor)
  await assert.rejects(call('ledger_report', { start: '2026-10-01', end: '2026-09-01' }))
  await assert.rejects(call('statement_reports', { period_type: 'invalid', year: 2026 }))
})
